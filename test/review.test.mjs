async function put(root, file, value) { await fs.mkdir(path.dirname(path.join(root, file)), { recursive: true }); await fs.writeFile(path.join(root, file), value); }
async function fixture(t, { beforeSource, afterSource, testDependent = false } = {}) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'opsx-review-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  await initProject(root);
  for (const artifact of ['proposal', 'design', 'tasks']) await put(root, `openspec/changes/review/${artifact}.md`, `# ${artifact}\n`);
  await put(root, 'src/shared.mjs', beforeSource ?? 'export const count = 1;\nexport const other = true;\n');
  await put(root, 'src/consumer.mjs', "import { count } from './shared.mjs';\nexport { count };\n");
  await put(root, 'main.mjs', "import './src/consumer.mjs';\n");
  await put(root, 'src/deleted.mjs', 'export const old = true;\n');
  await put(root, 'src/old-user.mjs', "import './deleted.mjs';\n");
  await put(root, 'src/removed-import.mjs', "import './shared.mjs';\n");
  if (testDependent) await put(root, 'test/shared.test.mjs', "import '../src/shared.mjs';\n");
  await enqueue(root, { action: 'preview', change: 'review' });
  const job = await claimNext(root, 'Review test agent');
  await put(job.workingDirectory, 'src/shared.mjs', afterSource ?? 'export const count = 2;\nexport const other = false;\nimport "./consumer.mjs";\n');
  await put(job.workingDirectory, 'src/removed-import.mjs', '// dependency removed\n');
  await put(job.workingDirectory, 'src/new.mjs', "import './shared.mjs';\nimport './missing.mjs';\n");
  await fs.unlink(path.join(job.workingDirectory, 'src/deleted.mjs'));
  await updateJob(root, job.id, job.claimToken, 'finish', 'Fixture preview');
  return { root, job };
}

test('file and line comments retain exact preview anchors and exports remain immutable after deletion', async t => {
  const { root, job } = await fixture(t);
  const file = await addComment(root, job.id, { file: 'src/shared.mjs', body: 'Consider the consumer behavior.' });
  const line = await addComment(root, job.id, { file: 'src/shared.mjs', side: 'proposed', start: '1', end: '2', body: 'Keep this contract stable.\n# quoted heading' });
  assert.equal(line.snippet, 'export const count = 2;\nexport const other = false;');
  assert.equal(line.preview, job.id);
  assert.match(line.beforeHash, /^[0-9a-f]{64}$/);
  await put(root, 'src/shared.mjs', '// working tree moved\n');
  const persisted = await listComments(root, job.id);
  assert.equal(persisted.length, 2);
  assert.equal(persisted[1].snippet, line.snippet);
  const exported = await exportFeedback(root, job.id);
  const document = (await feedbackExport(root, job.id, exported.id)).document;
  assert.match(document, /proposed lines 1–2/);
  assert.match(document, /> # quoted heading/);
  assert.match(document, /Do not implement code/);
  await deleteComment(root, job.id, file.id);
  await deleteComment(root, job.id, line.id);
  assert.deepEqual(await listComments(root, job.id), []);
  assert.equal((await feedbackExport(root, job.id, exported.id)).document, document);
  await assert.rejects(exportFeedback(root, job.id), /at least one comment/);
});

