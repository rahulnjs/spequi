test('dependency evidence follows transitive importers, includes added and deleted relationships, and ignores comments', async t => {
  const { root, job } = await fixture(t);
  const impact = await dependencyImpact(root, job.id, 'src/shared.mjs');
  assert.deepEqual(impact.direct, ['src/consumer.mjs', 'src/new.mjs', 'src/removed-import.mjs']);
  assert.deepEqual(impact.transitive, [{ file: 'main.mjs', via: 'src/consumer.mjs' }]);
  const removed = await dependencyImpact(root, job.id, 'src/deleted.mjs');
  assert.deepEqual(removed.direct, ['src/old-user.mjs']);
  const added = await dependencyImpact(root, job.id, 'src/new.mjs');
  assert.deepEqual(added.dependencies, [{ file: 'src/shared.mjs', state: 'added' }]);
  assert.ok(added.unresolved.some(item => item.reference === './missing.mjs'));
  assert.ok(!impact.transitive.some(item => item.file === 'src/shared.mjs'));
  const removedImport = await dependencyImpact(root, job.id, 'src/removed-import.mjs');
  assert.deepEqual(removedImport.dependencies, [{ file: 'src/shared.mjs', state: 'removed' }]);
  assert.deepEqual(references('// import "./fake.mjs"\nconst x = "import ./fake2.mjs";\nexport { a } from "./real.mjs";', 'app.mjs'), ['./real.mjs']);
  assert.deepEqual(references('@import "./base.css"; .a {background:url("./image.svg")}', 'app.css'), ['./base.css', './image.svg']);
});

