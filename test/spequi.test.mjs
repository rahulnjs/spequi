import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {initProject} from '../src/project.mjs';
import {createPreview} from '../src/previews.mjs';

test('Spequi initializes fresh, leaves every old store untouched, and excludes old state from previews',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'spequi fresh '));
 t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const oldFiles=new Map();
 for(const folder of ['.openspec-ui','.change-viewer']) for(const [file,value] of Object.entries({
  'config.json':'{"port":4999,"viewerVersion":"old","custom":true}',
  'reviews/retained.json':'{"body":"Preserve my review"}',
  'jobs/retained.json':'{"status":"queued","workingDirectory":"/old/location"}',
  'cli.mjs':'// Generated by openspec-ui. Keep this old launcher.\n'
 })){
  const target=path.join(root,folder,file);await fs.mkdir(path.dirname(target),{recursive:true});await fs.writeFile(target,value);oldFiles.set(target,value);
 }
 await fs.mkdir(path.join(root,'.agents/skills/opsx-ui'),{recursive:true});
 await fs.writeFile(path.join(root,'.agents/skills/opsx-ui/SKILL.md'),'Existing skill stays here.');
 const first=await initProject(root);await initProject(root);
 assert.equal(first.workspace,path.join(await fs.realpath(root),'.spequi'));
 for(const [file,value]of oldFiles)assert.equal(await fs.readFile(file,'utf8'),value);
 assert.equal(await fs.readFile(path.join(root,'.agents/skills/opsx-ui/SKILL.md'),'utf8'),'Existing skill stays here.');
 const config=JSON.parse(await fs.readFile(path.join(root,'.spequi/config.json')));
 assert.equal(config.port,4310);assert.equal(config.custom,undefined);
 assert.deepEqual(await fs.readdir(path.join(root,'.spequi/jobs')),[]);
 await assert.rejects(fs.access(path.join(root,'.spequi/reviews')));
 const skill=await fs.readFile(first.skill,'utf8');assert.match(skill,/^---\nname: spequi\n/);assert.match(skill,/npx spequi@latest init/);
 await fs.writeFile(path.join(root,'app.js'),'export const enabled = true;\n');
 await createPreview(root,'fresh-preview');
 const manifest=JSON.parse(await fs.readFile(path.join(root,'.spequi/previews/fresh-preview/manifest.json')));
 assert.ok(Object.hasOwn(manifest,'app.js'));
 assert.ok(!Object.keys(manifest).some(file=>file.startsWith('.openspec-ui/')||file.startsWith('.change-viewer/')||file.startsWith('.spequi/')));
 const launch=await fs.readFile(path.join(root,'.spequi/cli.mjs'),'utf8');assert.match(launch,/"spec":"spequi@0\.1\.0"/);assert.doesNotMatch(launch, /"spec":"openspec-ui@/);
 const ignore=await fs.readFile(path.join(root,'.gitignore'),'utf8');assert.equal(ignore.split('\n').filter(line=>line==='/.spequi/').length,1);
});
