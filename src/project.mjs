import * as fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { runtime, writeJSON, readJSON } from './files.mjs';
import { initializeAnalytics } from './analytics.mjs';

const skillFile = fileURLToPath(new URL('../skills/spequi/SKILL.md', import.meta.url));
const metadata = JSON.parse(await fs.readFile(new URL('../package.json', import.meta.url), 'utf8'));
export const viewerVersion = metadata.version;
const generated = '// Generated by spequi.';
async function writeGenerated(file, content) {
  const previous = await fs.readFile(file, 'utf8').catch(error => { if (error.code === 'ENOENT') return null; throw error; });
  if (previous === null || previous.startsWith(generated)) await fs.writeFile(file, content);
}
async function updateGitignore(root) {
  const file = path.join(root, '.gitignore');
  const content = await fs.readFile(file, 'utf8').catch(error => { if (error.code === 'ENOENT') return ''; throw error; });
  const lines = content.split(/\r?\n/).map(line => line.trim());
  const missing = ['.spequi', '.agents', '.claude', '.gigacode'].filter(directory => {
    // Use the last matching directory rule so a later explicit negation is repaired.
    const rules = lines.filter(line => line.replace(/^!/, '').replace(/^\//, '').replace(/\/$/, '') === directory);
    return !rules.length || rules.at(-1).startsWith('!');
  });
  if (!missing.length) return;
  const newline = content.includes('\r\n') ? '\r\n' : '\n';
  await fs.writeFile(file, `${content}${content && !content.endsWith('\n') ? newline : ''}${missing.map(directory => `/${directory}/`).join(newline)}${newline}`);
}

export async function installSkill(root, global = false) {
  const base = global ? os.homedir() : root;
  const target = path.join(base, '.agents/skills/spequi/SKILL.md');
  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.copyFile(skillFile, target);
  const command = path.join(base, '.claude/commands/spequi.md');
  await fs.mkdir(path.dirname(command), { recursive: true });
  const content = `---\nname: spequi\ndescription: Initialize and operate Spequi in the current agent session\n---\n\nRead and follow ${global ? '~/' : ''}.agents/skills/spequi/SKILL.md. User arguments: $ARGUMENTS\n`;
  await fs.writeFile(command, content);
  const gigacodeSkill = path.join(base, '.gigacode/skills/spequi/SKILL.md');
  await fs.mkdir(path.dirname(gigacodeSkill), { recursive: true });
  await fs.copyFile(skillFile, gigacodeSkill);
  const gigacodeCommand = path.join(base, '.gigacode/commands/spequi.md');
  await fs.mkdir(path.dirname(gigacodeCommand), { recursive: true });
  const gigacodeContent = `---\ndescription: Initialize and operate Spequi in the current agent session\n---\n\nRead and follow ${global ? '~/' : ''}.gigacode/skills/spequi/SKILL.md. User arguments: {{args}}\n`;
  await fs.writeFile(gigacodeCommand, gigacodeContent);
  return { skill: target, command, gigacode: { skill: gigacodeSkill, command: gigacodeCommand } };
}
export async function initProject(root) {
  root = await fs.realpath(root);
  for (const folder of ['jobs', 'previews', 'backups']) await fs.mkdir(runtime(root, folder), { recursive: true });
  const config = await readJSON(runtime(root, 'config.json')) || { version: 1, port: 4310, openspecDir: 'openspec' };
  if (config.viewerVersion !== viewerVersion) await writeJSON(runtime(root, 'config.json'), { ...config, viewerVersion });
  const entry = runtime(root, 'server.mjs');
  const launcher = await fs.readFile(new URL('../templates/cli.mjs', import.meta.url), 'utf8');
  await writeGenerated(runtime(root, 'cli.mjs'), launcher.replace('__SPEQUI_RUNTIME__', JSON.stringify({ name: metadata.name, version: viewerVersion, spec: `${metadata.name}@${viewerVersion}`, cli: fileURLToPath(new URL('../bin/spequi.mjs', import.meta.url)), npmCLI: process.env.npm_execpath || null })));
  await writeGenerated(entry, `${generated} Start this project's pinned viewer runtime.\nprocess.argv.splice(2, 0, 'start');\nawait import('./cli.mjs');\n`);
  await updateGitignore(root);
  const skill = await installSkill(root);
  await initializeAnalytics(root);
  return { root, workspace: runtime(root), ...skill };
}
