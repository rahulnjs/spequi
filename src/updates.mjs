import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFile, spawn } from 'node:child_process';
import { promisify } from 'node:util';
import { readJSON, runtime, exists, withLock } from './files.mjs';
import { listJobs, pendingStatuses } from './jobs.mjs';

const exec = promisify(execFile);
const packageRoot = fileURLToPath(new URL('../', import.meta.url));
const metadata = JSON.parse(await fs.readFile(new URL('../package.json', import.meta.url), 'utf8'));
const release = value => /^\d+\.\d+\.\d+$/.test(value || '');
const newer = (a, b) => {
  const left = a.split('.').map(Number), right = b.split('.').map(Number);
  for (let i = 0; i < 3; i++) if (left[i] !== right[i]) return left[i] > right[i];
  return false;
};

async function npmEntry() {
  const candidates = [process.env.npm_execpath, path.join(path.dirname(process.execPath), 'node_modules/npm/bin/npm-cli.js')];
  for (const directory of (process.env.PATH || '').split(path.delimiter).filter(Boolean)) {
    candidates.push(path.join(directory, 'node_modules/npm/bin/npm-cli.js'));
    for (const name of ['npm', 'npm.cmd']) {
      const resolved = await fs.realpath(path.join(directory, name)).catch(() => null);
      if (resolved?.endsWith('npm-cli.js')) candidates.push(resolved);
    }
  }
  for (const file of candidates) if (file && await fs.stat(file).then(stat => stat.isFile(), () => false)) return file;
  throw new Error('npm could not be found. Install Node.js with npm and retry.');
}

export async function checkForUpdate(root) {
  const current = metadata.version;
  try {
    const { stdout } = await exec(process.execPath, [await npmEntry(), 'view', `${metadata.name}@latest`, 'version', '--json', '--fetch-retries=0', '--fetch-timeout=2500'], { cwd: root, timeout: 4000, maxBuffer: 4096, windowsHide: true });
    const latest = JSON.parse(stdout);
    if (!release(latest) || !release(current)) throw new Error('Invalid release version');
    return { current, latest, available: newer(latest, current), development: await exists(path.join(packageRoot, '.git')) };
  } catch { return { current, available: false, unavailable: true }; }
}

export async function updateRuntime(root) {
  if (await exists(path.join(packageRoot, '.git'))) throw new Error('This runtime is a local source checkout. Update the checkout yourself, then run node bin/spequi.mjs init; published updates will not replace local code.');
  return withLock(runtime(root, 'update.lock'), async () => {
    const connection = await readJSON(runtime(root, 'server.json'));
    if (connection?.pid) {
      let live = false;
      try { process.kill(connection.pid, 0); live = true; } catch (error) { if (error.code === 'EPERM') live = true; }
      if (live) throw new Error('Stop this project’s Spequi server before updating, then restart it and reload the Spequi skill. Requests and project state are retained.');
    }
    if ((await listJobs(root)).some(job => pendingStatuses.includes(job.status) && job.status !== 'queued')) throw new Error('Finish or resolve the active request before updating. Its saved state has been kept.');
    for (const name of ['cli.mjs', 'server.mjs']) {
      const content = await fs.readFile(runtime(root, name), 'utf8').catch(error => { if (error.code === 'ENOENT') return ''; throw error; });
      if (content && !content.startsWith('// Generated by spequi.')) throw new Error(`Custom .spequi/${name} was preserved. Reconcile it with the generated launcher before updating.`);
    }
    const shipped = await fs.readFile(new URL('../skills/spequi/SKILL.md', import.meta.url), 'utf8');
    for (const relative of ['.agents/skills/spequi/SKILL.md', '.gigacode/skills/spequi/SKILL.md']) {
      const content = await fs.readFile(path.join(root, relative), 'utf8').catch(error => { if (error.code === 'ENOENT') return ''; throw error; });
      if (content && content !== shipped) throw new Error(`Local changes in ${relative} were preserved. Use the project’s pinned runtime to update, or reconcile those changes first.`);
    }
    const wrappers = {
      '.claude/commands/spequi.md': '---\nname: spequi\ndescription: Initialize and operate Spequi in the current agent session\n---\n\nRead and follow .agents/skills/spequi/SKILL.md. User arguments: $ARGUMENTS\n',
      '.gigacode/commands/spequi.md': '---\ndescription: Initialize and operate Spequi in the current agent session\n---\n\nRead and follow .gigacode/skills/spequi/SKILL.md. User arguments: {{args}}\n'
    };
    for (const [relative, expected] of Object.entries(wrappers)) {
      const content = await fs.readFile(path.join(root, relative), 'utf8').catch(error => { if (error.code === 'ENOENT') return ''; throw error; });
      if (content && content !== expected) throw new Error(`Custom ${relative} was preserved. Reconcile the command wrapper before updating.`);
    }
    const cli = await npmEntry();
    const latest = await checkForUpdate(root);
    if (latest.unavailable) throw new Error('Could not check the configured npm registry. Your current runtime is unchanged; retry when online or fix the project’s npm registry settings.');
    if (!latest.available && newer(metadata.version, latest.latest)) throw new Error('The configured registry has an older release. Current runtime retained.');
    await new Promise((resolve, reject) => {
      const child = spawn(process.execPath, [cli, 'exec', '--yes', '--prefer-online', `--package=${metadata.name}@${latest.latest}`, '--', metadata.name, 'init', '--root', root], { cwd: root, stdio: 'inherit', shell: false });
      child.once('error', reject);
      child.once('exit', code => code === 0 ? resolve() : reject(new Error('Update failed. Project requests and data were retained; retry the update.')));
    });
    const config = await readJSON(runtime(root, 'config.json'));
    if (config?.viewerVersion !== latest.latest) throw new Error('Could not confirm the new runtime. Re-run initialization with the intended package version.');
    return { version: config.viewerVersion, next: 'Start node .spequi/server.mjs, reload the Spequi skill from disk, and reattach the agent. Existing requests are retained.' };
  }, { waitMs: 0 });
}
